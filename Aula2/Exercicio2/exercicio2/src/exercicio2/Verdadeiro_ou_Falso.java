package exercicio2;
/* Exercicio 2 Da Lista*/
public class Verdadeiro_ou_Falso {

	public static void main(String[] args) {
		
		boolean v1 = true;
		boolean v2 = false;
		boolean v3 = true;
		
		System.out.println("Variavel 1:" + v1);
		System.out.println("Variavel 2:" + v2);
		System.out.println("Variavel 3:" + v3);
		
		
		if(v1 == true) {
			System.out.println("Variavel 1 e Verdadeira");
		}else {
			System.out.println("Variavel 1 e Falsa");
		}
		
		if(v2 == true) {
			System.out.println("Variavel 2 e Verdadeira");
		}else {
			System.out.println("Variavel 2 e Falsa");
		}
		
		if(v3 == true) {
			System.out.println("Variavel 3 e Verdadeira");
		}else {
			System.out.println("Variavel 3 e Falsa");
		}
	}
	
}
